SKILL_NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
PROFILE_BUNDLES = ["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-headless"]
SESSION_FILE_RE = re.compile(r"^session(?:\.v(\d+))?\.jsonl(\.zstd)?$")


def _yaml_string(value: str) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def _profile_name(domain: str, run_id: str, fingerprint: str) -> str:
    domain_slug = re.sub(r"[^a-z0-9]+", "-", domain.lower()).strip("-")[:24] or "domain"
    head = str(run_id).split("/", 1)[0]
    match = re.search(r"-(agg|seq)(\d+)(?:-s(\d+))?", head)
    if match:
        mode, k, seed = match.group(1), match.group(2), match.group(3) or "0"
        variant = f"{mode}-k{k}-s{seed}"
    else:
        variant = store.sha256_text(str(run_id))[:8]
    return f"md-{domain_slug}-dsh-{variant}-{fingerprint[:8]}"


def _write_profile(
    home: Path,
    profile_id: str,
    tree: dict[str, str],
    *,
    provider: str,
    model: str,
    include_answerer: bool = True,
) -> Path:
    profile = Path(home) / "profiles" / profile_id
    if profile.exists():
        shutil.rmtree(profile)
    profile.mkdir(parents=True)
    manifest = {
        "name": f"morphd-{profile_id}",
        "private": True,
        "dsh": {"profile": {"bundles": PROFILE_BUNDLES}},
    }
    store.atomic_write_json(profile / "package.json", manifest)
    patch_lines = [
        "# generated by morphd; the candidate tree cannot edit this file.",
        "# fixed execution policy: workspace-write + ask, no danger-full-access preset.",
    ]
    if include_answerer:
        patch_lines += [
            "- insert:",
            "    - id: morphd-approver",
            "      name: ./morphd-approver.mjs",
        ]
    patch_lines += [
        "- id: sandbox-policy",
        "  config:",
        f"    mode: {config.DSH_SANDBOX_MODE}",
        "    workspaceRoot: !!js process.cwd()",
        "- id: approval",
        "  config:",
        f"    policy: {config.DSH_APPROVAL_POLICY}",
        "- id: permission",
        "  config:",
        "    presets:",
        "      read-only:",
        "        sandbox: read-only",
        "        approval: ask",
        "      workspace-write:",
        "        sandbox: workspace-write",
        "        approval: ask",
        "- id: agent-default-model",
        "  config:",
        f"    provider: {_yaml_string(provider)}",
        f"    model: {_yaml_string(model)}",
        "",
    ]
    store.atomic_write_text(profile / "cordis.patch.yml", "\n".join(patch_lines))
    if include_answerer:
        approvals.install_plugin(profile / "morphd-approver.mjs")
    skills_root = Path(home) / "skills"
    for rel, text in tree.items():
        if rel.startswith("skills/"):
            target = skills_root / rel[len("skills/") :]
            store.atomic_write_text(target, text)
    return profile


def _skill_names(tree: dict[str, str]) -> list[str]:
    names = []
    for rel in tree:
        match = re.fullmatch(r"skills/([^/]+)/SKILL\.md", rel)
        if match:
            names.append(match.group(1))
    return sorted(names)


def _message_text(message: dict) -> str:
    content = message.get("content")
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts = []
    for block in content:
        if isinstance(block, dict) and block.get("type") == "text":
            text = block.get("text")
            if isinstance(text, str) and text.strip():
                parts.append(text)
    return "\n".join(parts).strip()


def _clip(text: str, limit: int) -> str:
    text = "" if text is None else str(text).replace("\x00", "")
    if limit <= 0 or len(text) <= limit:
        return text
    return text[:limit] + f"…(+{len(text) - limit} chars)"


def parse_session_bytes(data: bytes) -> tuple[dict, list[dict]]:
    if data[:4] == b"\x28\xb5\x2f\xfd":
        import zstandard

        with zstandard.ZstdDecompressor().stream_reader(data) as reader:
            data = reader.read()
    rows = []
    for line in data.decode("utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except ValueError:
            continue
        if isinstance(row, dict):
            rows.append(row)
    if not rows or rows[0].get("type") != "session":
        raise RuntimeError_("session log has no physical header")
    return rows[0], rows[1:]


def _session_files(home: Path) -> list[Path]:
    root = Path(home) / "sessions"
    out = []
    for path in root.rglob("session*.jsonl*"):
        if path.is_file() and SESSION_FILE_RE.match(path.name):
            out.append(path)
    return sorted(out, key=lambda p: (p.stat().st_mtime if p.exists() else 0, str(p)))


def _newest_session(home: Path, session_id: str | None = None) -> tuple[Path, dict, list[dict]] | None:
    files = _session_files(home)
    if not files:
        return None
    candidates = files[::-1]
    for path in candidates:
        try:
            header, events = parse_session_bytes(path.read_bytes())
        except Exception:
            continue
        if session_id and str(header.get("id")) != session_id:
            continue
        return path, header, events
    if session_id:
        return None
    path = candidates[0]
    header, events = parse_session_bytes(path.read_bytes())
    return path, header, events


def _stream_session_id(path: Path) -> str | None:
    try:
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if isinstance(row, dict) and row.get("type") == "session":
                return str(row.get("sessionId") or row.get("id") or "") or None
    except OSError:
        return None
    return None


def _turn_reason(events: list[dict]) -> dict:
    reason: dict = {}
    for event in events:
        if event.get("type") == "turn/end":
            value = (event.get("data") or {}).get("reason")
            if isinstance(value, dict):
                reason = value
    return reason


def _usage_events(events: list[dict]) -> list[dict]:
    return [
        event
        for event in events
        if event.get("type") == "assistant/message"
        and isinstance((event.get("data") or {}).get("usage"), dict)
    ]


def _tool_events(events: list[dict]) -> list[dict]:
    calls: dict[str, str] = {}
    out: list[dict] = []
    for event in events:
        data = event.get("data") or {}
        if event.get("type") == "tool/call":
            calls[str(data.get("callId") or "")] = str(data.get("name") or "tool")
        elif event.get("type") == "tool/result":
            message = data.get("message") or {}
            call_id = str(message.get("toolCallId") or message.get("callId") or "")
            tool = calls.get(call_id, "tool")
            error = bool(message.get("isError"))
            signature = ""
            if error:
                meta = data.get("error") or {}
                signature = str(meta.get("code") or meta.get("name") or "") or _message_text(
                    message
                )[:200]
            out.append({"tool": tool, "error": error, "signature": signature})
    return out


def render_session_events(
    events: list[dict], *, obs_trunc: int, args_trunc: int = 400
) -> str:
    lines: list[str] = []
    for event in events:
        etype = event.get("type")
        data = event.get("data") or {}
        if etype == "user/message":
            message = data.get("message") if isinstance(data.get("message"), dict) else data
            source = message.get("source") or {}
            text = _message_text(message)
            if text:
                if isinstance(source, dict) and source.get("kind") == "user":
                    lines.append(f"[USER] {_clip(text, obs_trunc)}")
                else:
                    lines.append(f"[HARNESS] {_clip(text, obs_trunc)}")
        elif etype == "assistant/message":
            message = data.get("message") or {}
            text = _message_text(message)
            if text:
                lines.append(f"[ASSISTANT] {_clip(text, obs_trunc)}")
        elif etype == "tool/call":
            name = data.get("name") or "tool"
            args = data.get("arguments") or ""
            lines.append(f"[ACTION] {name}: {_clip(args, args_trunc)}")
        elif etype == "tool/result":
            message = data.get("message") or {}
            text = _message_text(message)
            error = " ERROR" if message.get("isError") else ""
            lines.append(f"[OBSERVATION{error}] {_clip(text, obs_trunc)}")
        elif etype == "turn/end":
            reason = data.get("reason") or {}
            kind = reason.get("kind") if isinstance(reason, dict) else reason
            lines.append(f"[HARNESS] turn ended: {kind}")
        elif etype == "approval/decided":
            lines.append(f"[HARNESS] approval {data.get('outcome')}")
        elif etype in {"assistant/attempt"}:
            lines.append("[HARNESS] attempt without a committed message")
    rendered = "\n".join(lines).strip()
    return rendered or "(no parseable events in session log)"


class DshSubstrate:
    name = "dsh"

    def __init__(self, *, provider: str, model: str, launcher=None) -> None:
        self.provider = provider
        self.model = model
        self._launcher = launcher

    def surface(self):
        return DSH_SURFACE

    def materialise(self, tree_dir: Path, spec, ctx) -> object:
        base = _upstream.substrate("base")
        tree = HT.read_tree(DSH_SURFACE, tree_dir)
        dest = Path(ctx.get("dest") or tempfile.mkdtemp(prefix="morphd-dsh-"))
        home = dest / "runtime_home"
        profile_id = str(ctx.get("profile_id") or _profile_name("domain", "run", store.payload_hash(tree)))
        _write_profile(
            home,
            profile_id,
            tree,
            provider=str(ctx.get("provider") or self.provider),
            model=str(ctx.get("model") or self.model),
            include_answerer=True,
        )
        overlay = dest / "workspace_overlay"
        overlay.mkdir(parents=True, exist_ok=True)
        for rel, text in tree.items():
            if rel == "AGENTS.md" or rel.startswith("scripts/"):
                store.atomic_write_text(overlay / rel, text)
        credentials = home / ".credentials.yaml"
        if credentials.exists():
            raise RuntimeError_("variant DSH_HOME must not contain .credentials.yaml")
        fingerprint = store.payload_hash(tree)
        return base.Install(
            staging_dir=home,
            fingerprint=fingerprint,
            extras={
                "profile_id": profile_id,
                "workspace_overlay": str(overlay),
                "dsh_home": str(home),
            },
        )

    def execute(self, task_ref, install, run_ids, timeout):
        if self._launcher is None:
            raise RuntimeError_(
                "DshSubstrate.execute requires a launcher; the adapter owns execution"
            )
        base = _upstream.substrate("base")
        return self._launcher(
            base.RunRequest(task_ref=task_ref, run_ids=tuple(run_ids), timeout=int(timeout)),
            install,
        )

    def read_trajectory(self, stream_path: Path, *, obs_trunc: int, max_chars: int, args_trunc: int = 400) -> str:
        try:
            _, events = parse_session_bytes(Path(stream_path).read_bytes())
        except Exception:
            lines = []
            for line in Path(stream_path).read_text(encoding="utf-8", errors="replace").splitlines():
                try:
                    row = json.loads(line)
                except ValueError:
                    continue
                if isinstance(row, dict):
                    lines.append(json.dumps(row, ensure_ascii=False)[:max_chars])
            return "\n".join(lines)[:max_chars] or "(no parseable events)"
        rendered = render_session_events(events, obs_trunc=obs_trunc, args_trunc=args_trunc)
        if len(rendered) > max_chars:
            rendered = rendered[:max_chars] + f"…(+{len(rendered) - max_chars} chars)"
        return rendered

    def preflight(self) -> None:
        pass


class DshAdapter(BaseAdapter):
    runtime = "dsh"
    substrate_name = "dsh"

    def __init__(self, *, proposer_channel: str = "claude_cli", proposer_model: str = "", **kwargs):
        super().__init__(**kwargs)
        self.substrate = DshSubstrate(provider=self.settings.dsh_provider, model=self.model)
        from ..runtimes.prompts import make_spec

        self.spec = make_spec(
            runtime=self.runtime,
            substrate=self.substrate_name,
            settings=self.settings,
            install_mode="workspace_agents_md",
            allow_subagents=False,
            proposer_channel=proposer_channel,
            proposer_model=proposer_model,
        )

    def _hard_always_on_bytes(self) -> int:
        return 65_536

    def validate_tree(self, tree: dict[str, str]) -> None:
        super().validate_tree(tree)
        problems = []
        for name in _skill_names(tree):
            if not SKILL_NAME_RE.fullmatch(name):
                problems.append(
                    f"skills/{name}/SKILL.md: dsh requires kebab-case skill names"
                )
        if "sub_agents/README.md" in tree or any(
            rel.startswith("sub_agents/") for rel in tree
        ):
            problems.append(
                "sub_agents are disabled on the dsh runtime in v1 (preset installation "
                "is not implemented); use skills and scripts instead"
            )
        if problems:
            raise ValueError(" | ".join(problems))

    def _runtime_controls(self) -> dict:
        return {
            "provider": self.settings.dsh_provider,
            "sandbox_mode": config.DSH_SANDBOX_MODE,
            "approval_policy": config.DSH_APPROVAL_POLICY,
            "sampling": "provider-default-pinned-by-version-and-model",
            "profile_bundles": sorted(PROFILE_BUNDLES),
            "forbid_credentials_file": True,
        }

    def _binary(self) -> str:
        binary = self.settings.binary_for("dsh")
        resolved = shutil.which(binary) if os.sep not in binary else binary
        if not resolved or not Path(resolved).exists():
            raise RuntimeError_(
                f"dsh CLI not found ({binary!r}); install dsh {self.settings.pins['dsh']} "
                "and set MORPHD_DSH_BIN if it is not on PATH"
            )
        return str(resolved)

    def _runtime_version(self) -> str:
        if self._version_cache is not None:
            return self._version_cache
        proc = subprocess.run(
            winproc.command_line(self._binary(), ["--version"]),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=20,
            check=False,
        )
        out = (proc.stdout or proc.stderr or "").strip()
        if proc.returncode != 0 or not out:
            raise RuntimeError_(f"cannot read dsh version: exit {proc.returncode} {out[:200]}")
        self._version_cache = out.splitlines()[0].strip()
        return self._version_cache

    def _preflight_runtime(self) -> dict:
        problems = []
        target = self.settings.dsh_target_home()
        if target is not None:
            if target == Path.home() / ".dsh":
                problems.append("MORPHD_DSH_TARGET_HOME must never be the default ~/.dsh")
            if target.is_dir() and (target / "settings.yaml").exists() and any(
                str(path.name).startswith("_backup_profile_") for path in target.iterdir()
            ):
                problems.append(
                    f"MORPHD_DSH_TARGET_HOME looks like a third-party product home: {target}"
                )
        if self.settings.dsh_provider == "deepseek-official" and not os.environ.get(
            "DEEPSEEK_API_KEY", ""
        ).strip():
            problems.append(
                "DEEPSEEK_API_KEY is not set; headless credentials come from the process "
                "environment because the variant home must not contain .credentials.yaml"
            )
        node = shutil.which("node")
        node_version = ""
        if node is None:
            problems.append("node is not on PATH (dsh needs ^22.19.0 || >=24.0.0)")
        else:
            proc = subprocess.run(
                [node, "--version"], capture_output=True, text=True, timeout=10, check=False
            )
            node_version = (proc.stdout or "").strip().lstrip("v")
            if node_version:
                major, _, minor = node_version.partition(".")
                try:
                    minor_i = int(minor.split(".")[0])
                except ValueError:
                    minor_i = 0
                major_i = int(major)
                if not ((major_i == 22 and minor_i >= 19) or major_i >= 24):
                    problems.append(
                        f"node {node_version} is outside the supported range ^22.19.0 || >=24.0.0"
                    )
        if problems:
            raise RuntimeError_("; ".join(problems))
        detail = {
            "provider": self.settings.dsh_provider,
            "node_version": node_version,
            "controller": {"sandbox": config.DSH_SANDBOX_MODE, "approval": config.DSH_APPROVAL_POLICY},
        }
        if os.environ.get("MORPHD_DSH_DUMP_CHECK", "1") not in {"0", "false"}:
            with tempfile.TemporaryDirectory(prefix="morphd-dsh-preflight-") as tmp:
                home = Path(tmp)
                profile = _write_profile(
                    home,
                    "md-preflight",
                    {"AGENTS.md": "preflight\n"},
                    provider=self.settings.dsh_provider,
                    model=self.model,
                    include_answerer=True,
                )
                env = dict(os.environ)
                env["DSH_HOME"] = str(home)
                proc = subprocess.run(
                    winproc.command_line(
                        self._binary(), ["--profile", profile.name, "--dump-config"]
                    ),
                    cwd=tmp,
                    env=env,
                    capture_output=True,
                    text=True,
                    timeout=120,
                    check=False,
                )
                if proc.returncode != 0:
                    raise RuntimeError_(
                        "dsh profile preflight failed: "
                        + (proc.stderr or proc.stdout or "")[-800:].strip()
                    )
                plugin = profile / "morphd-approver.mjs"
                node_check = subprocess.run(
                    [node or "node", "--check", plugin.name],
                    cwd=profile,
                    capture_output=True,
                    text=True,
                    timeout=30,
                    check=False,
                )
                detail["dump_config_ok"] = True
                detail["approver_syntax_ok"] = node_check.returncode == 0
                if node_check.returncode != 0:
                    detail["approver_syntax_warning"] = (
                        node_check.stderr or node_check.stdout or ""
                    )[-500:].strip()
        return detail

    def controlled_variables(self) -> dict:
        return super().controlled_variables()

    def _prepare_run(
        self,
        *,
        task: TaskContract,
        source_tree: Path,
        run_dir: Path,
        workspace: Path,
        run_id: str,
        meta: dict,
    ) -> PreparedRun:
        for rel in ("CLAUDE.md", "CLAUDE.local.md", "AGENTS.local.md"):
            path = workspace / rel
            if path.exists():
                path.unlink()
        shutil.rmtree(workspace / ".dsh", ignore_errors=True)
        shutil.rmtree(workspace / ".agents" / "skills", ignore_errors=True)
        tree = HT.read_tree(DSH_SURFACE, source_tree)
        fingerprint = store.payload_hash(tree)
        profile_id = _profile_name(task.domain, run_id, fingerprint)
        install = self.substrate.materialise(
            source_tree,
            self.spec,
            {
                "dest": run_dir,
                "profile_id": profile_id,
                "provider": self.settings.dsh_provider,
                "model": self.model,
            },
        )
        env_home = Path(install.extras["dsh_home"])
        overlay = Path(install.extras["workspace_overlay"])
        shutil.copytree(overlay, workspace, dirs_exist_ok=True)
        (run_dir / "agents_home").mkdir(exist_ok=True)
        (run_dir / "home").mkdir(exist_ok=True)
        if (env_home / ".credentials.yaml").exists():
            raise RuntimeError_("variant DSH_HOME contains .credentials.yaml")
        if env_home.resolve() == (Path.home() / ".dsh").resolve():
            raise RuntimeError_("variant DSH_HOME must never be the default ~/.dsh")
        return PreparedRun(
            runtime_home=env_home,
            workspace=workspace,
            profile_id=str(install.extras["profile_id"]),
            extras={
                "profile_path": str(env_home / "profiles" / install.extras["profile_id"]),
                "fingerprint": install.fingerprint,
            },
        )

    def _invoke_turn(
        self,
        *,
        task: TaskContract,
        run_dir: Path,
        workspace: Path,
        runtime_home: Path,
        prompt: str,
        session_id: str | None,
        turn_index: int,
        timeout: int,
    ) -> TurnResult:
        events_dir = run_dir / "events"
        events_dir.mkdir(exist_ok=True)
        stream_path = events_dir / f"dsh-turn-{turn_index + 1}-stream.jsonl"
        stderr_path = events_dir / f"dsh-turn-{turn_index + 1}-stderr.log"
        profile_id = meta_profile(run_dir)
        cmd = winproc.command_line(self._binary(), ["--profile", profile_id, "--json"])
        if session_id:
            cmd += ["--session-id", session_id]
        cmd += ["--", prompt]
        env = dict(os.environ)
        env.update(
            {
                "DSH_HOME": str(runtime_home),
                "DSH_AGENTS_HOME": str(run_dir / "agents_home"),
                "HOME": str(run_dir / "home"),
                "MORPHD_APPROVER_CONFIG": str(run_dir / "approver.json"),
                "MORPHD_APPROVALS_LOG": str(run_dir / "approvals.jsonl"),
                "NO_COLOR": "1",
            }
        )
        timed_out = False
        try:
            with open(stream_path, "wb") as out, open(stderr_path, "wb") as err:
                proc = subprocess.run(
                    cmd,
                    cwd=workspace,
                    env=env,
                    stdout=out,
                    stderr=err,
                    timeout=timeout,
                    check=False,
                )
            exit_code = proc.returncode
        except subprocess.TimeoutExpired:
            timed_out = True
            exit_code = 124
        session_from_stream = _stream_session_id(stream_path)
        found = _newest_session(runtime_home, session_id or session_from_stream)
        if found is None:
            stderr = store.read_text_limited(stderr_path, 4000)
            return TurnResult(
                exit_code=exit_code,
                achieved=False if exit_code != 0 or timed_out else None,
                reason="timeout" if timed_out else "no-session-log",
                bucket="error",
                session_id=session_id or session_from_stream,
                stderr=stderr,
                turns=0,
                can_continue=False,
            )
        path, header, events = found
        sid = str(header.get("id") or session_from_stream or "")
        cursor_path = run_dir / "events" / "dsh-cursor.json"
        cursor = store.read_json(cursor_path) or {}
        last_seq = int(cursor.get(sid, -1))
        new_events = [
            event for event in events if int(event.get("seq", 0)) > last_seq
        ]
        max_seq = max([int(e.get("seq", 0)) for e in events] + [last_seq])
        store.atomic_write_json(cursor_path, {**cursor, sid: max_seq})
        reason = _turn_reason(new_events)
        kind = str(reason.get("kind") or "")
        if kind == "completed":
            achieved = True
        elif kind in {"error", "blocked", "max-tokens", "aborted"}:
            achieved = False
        else:
            achieved = None
        usage = _merge_dsh_usage(new_events)
        tool_events = _tool_events(new_events)
        steps = sum(1 for event in new_events if event.get("type") == "step/end")
        assistant_text = ""
        for event in new_events:
            if event.get("type") == "assistant/message":
                text = _message_text((event.get("data") or {}).get("message") or {})
                if text:
                    assistant_text = text
        full_session = events_dir / "session.jsonl"
        store.atomic_write_bytes(full_session, _serialize_rows(header, events))
        stderr = store.read_text_limited(stderr_path, 4000)
        if timed_out:
            achieved = False
            kind = "timeout"
        return TurnResult(
            exit_code=exit_code,
            achieved=achieved,
            reason=kind or ("exit-" + str(exit_code) if exit_code else ""),
            bucket=metrics.bucket_of(kind) if kind else "unavailable",
            session_id=sid or None,
            usage=usage,
            tool_events=tool_events,
            turns=steps or (1 if new_events else 0),
            final_text=assistant_text,
            stderr=stderr,
            can_continue=bool(sid),
        )

    def _trajectory_path(self, run_dir: Path) -> Path:
        return Path(run_dir) / "events" / "session.jsonl"


def meta_profile(run_dir: Path) -> str:
    meta = store.read_json(Path(run_dir) / "meta.json") or {}
    profile = meta.get("profile_id")
    if not profile:
        raise RuntimeError_("run meta has no profile_id")
    return str(profile)


def _merge_dsh_usage(events: list[dict]) -> dict:
    merged = {
        "inputTokens": 0,
        "outputTokens": 0,
        "cacheReadTokens": 0,
        "cacheWriteTokens": 0,
        "reasoningTokens": 0,
    }
    present = False
    for event in _usage_events(events):
        usage = (event.get("data") or {}).get("usage") or {}
        present = True
        for key in merged:
            try:
                merged[key] += int(usage.get(key, 0) or 0)
            except (TypeError, ValueError):
                pass
    merged["present"] = present
    return merged


def _serialize_rows(header: dict, events: list[dict]) -> bytes:
    rows = [header, *events]
    return "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows).encode("utf-8")


